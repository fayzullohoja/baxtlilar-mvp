import { test, expect } from "vitest";
import { containsContact } from "./schemas";

// SU-1: анти-контакт фильтр ловил мессенджеры только как точное слово — падежные
// (склонённые) формы, которые реально печатают, проскакивали.

test("ловит склонённые формы мессенджеров (SU-1)", () => {
  for (const s of [
    "добавь в инсту",
    "пиши в телегу",
    "я сижу в вотсапе",
    "скинь свой вайбер",
    "го в дискорде",
    "мой инстаграм тут",
    "пиши в телеграме",
    "лучше в скайпе",
  ]) {
    expect(containsContact(s), s).toBe(true);
  }
});

test("НЕ ловит легитимные слова со схожим корнем (без ложных срабатываний)", () => {
  for (const s of [
    "инстинкт мне подсказал",
    "обратитесь в инстанцию",
    "прочитал инструкцию по сборке",
    "получили телеграф вчера",
  ]) {
    expect(containsContact(s), s).toBe(false);
  }
});

test("регрессия: существующие точные формы всё ещё ловятся", () => {
  for (const s of [
    "мой telegram открыт",
    "пиши в тг",
    "есть инста",
    "используй whatsapp",
    "добавь telegram",
  ]) {
    expect(containsContact(s), s).toBe(true);
  }
});
