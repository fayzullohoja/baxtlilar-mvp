/**
 * Пределы полей анкеты - в одном месте.
 *
 * Зачем. Каждый такой предел был записан в трёх-четырёх местах: в схеме
 * (сервер), в форме (сколько даёт выбрать и что пишет в подписи) и в админском
 * реестре полей. Копии разъехались, и разъехались так, что это видит человек:
 *
 *   - «жизненные ценности»: сервер принимает пять, форма позволяет выбрать
 *     пять, а подпись под ней считает «/3». Предел я сам поднимал с трёх до
 *     пяти в начале работы - и поправил схему с базой, но не подпись и не
 *     админку. Правка была неполной ровно потому, что мест оказалось четыре;
 *   - «о себе»: поле даёт напечатать тысячу символов, сервер режет на пятистах.
 *     Человек пишет длинный текст, жмёт «сохранить» и получает отказ. Хуже
 *     запрета только запрет, о котором узнаёшь после работы;
 *   - админский реестр режет ценности и досуг на трёх - то есть оператор не
 *     может сохранить анкету человека, законно выбравшего пять.
 *
 * Правило простое: предел живёт здесь, всё остальное на него ссылается.
 * Число, вписанное руками во второе место, рано или поздно разойдётся - в этом
 * проекте это уже произошло трижды.
 */

/** Сколько жизненных ценностей можно выбрать. */
export const LIFE_VALUES_MIN = 1;
export const LIFE_VALUES_MAX = 5;

/** Сколько занятий в свободное время можно выбрать. */
export const FREE_TIME_MIN = 1;
export const FREE_TIME_MAX = 5;

/** Длина текста «О себе». Нижняя граница не формальность: слишком короткий
 *  текст не даёт собеседнику ничего, ради чего стоит начинать разговор. */
export const BIO_MIN = 50;
export const BIO_MAX = 500;

/** Сколько стран можно указать в предпочтениях партнёра. */
export const PARTNER_COUNTRIES_MAX = 3;
