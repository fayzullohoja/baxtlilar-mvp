/**
 * Ширины превью и приписывание ширины к подписанной ссылке.
 *
 * Отдельно от thumbs.ts намеренно: сама генерация превью серверная
 * ("server-only" + доступ к диску), а таблицы админки и экраны мини-аппа -
 * клиентские компоненты, и им нужна только эта пара функций. Общий модуль тянул
 * бы серверный код в браузерный бандл.
 *
 * КАК ВЫБИРАТЬ ШИРИНУ. Превью делается с fit:"inside": ограничивается ДЛИННАЯ
 * сторона, пропорции сохраняются. А в вёрстке картинка почти всегда стоит с
 * objectFit:"cover" в квадратной или почти квадратной коробке, и там размер
 * определяет КОРОТКАЯ сторона. У портретного снимка 3:4 короткая сторона выходит
 * примерно 0.75 от запрошенной ширины, у 3024x4032 с телефона - и вовсе 0.75.
 * Значит запас нужен двойной: на пропорции и на плотность экрана (до 3x).
 *
 *   коробка 24-32 px  ->  160  (короткая сторона ~120 при нужных 72-96)
 *   коробка 48-64 px  ->  320  (короткая ~240 при нужных 144-192)
 *   карточка в узкой колонке админки -> 640
 *   фото на всю ширину телефона -> 1280 (на 3x это ~1170 device px)
 *
 * Больше четырёх значений заводить не стоит: каждая ширина - отдельная запись в
 * кеше и отдельное пережатие.
 */

export const THUMB_WIDTHS = [160, 320, 640, 1280] as const;
export type ThumbWidth = (typeof THUMB_WIDTHS)[number];

/**
 * Ширина из query, только из белого списка. Иначе null - отдаём оригинал.
 *
 * Белый список здесь не украшение: ширина НЕ входит в подпись ссылки, то есть
 * её подставляет клиент. Произвольное значение означало бы, что любой держатель
 * законной ссылки может заставить сервер пережать один и тот же файл сколько
 * угодно раз подряд. Доступа к чужому это не даёт, а процессор жжёт.
 */
export function parseThumbWidth(raw: string | null | undefined): ThumbWidth | null {
  if (!raw) return null;
  const n = Number(raw);
  return (THUMB_WIDTHS as readonly number[]).includes(n) ? (n as ThumbWidth) : null;
}

/**
 * Добавить ширину к подписанной ссылке.
 *
 * Возвращает null на пустом входе, чтобы вызывающий писал `thumb(url, 320) ?? url`
 * и не терял картинку, если ссылки нет.
 */
export function thumb(url: string | null | undefined, width: ThumbWidth): string | null {
  if (!url) return null;
  return `${url}${url.includes("?") ? "&" : "?"}w=${width}`;
}
