import "server-only";

/**
 * Ключ пары для таблицы chats.
 *
 * Чаты хранятся с нормализованным порядком участников: RPC создаёт строку как
 * `insert into chats(user_a, user_b) values (least(...), greatest(...))`, и на
 * пару навешен уникальный индекс `chats_pair`. Поэтому найти чат двух людей
 * можно одним равенством по обеим колонкам - без перебора двух порядков,
 * которого query-builder всё равно не умеет (в нём нет or()).
 *
 * Почему сравнение строк здесь эквивалентно least() над uuid: Postgres
 * сравнивает uuid побайтово, а канонический текстовый вид - это те же байты в
 * нижнем регистре шестнадцатеричными парами с дефисами на фиксированных
 * позициях. Для такой формы лексикографический порядок совпадает с побайтовым.
 * Эквивалентность не оставлена на веру - её проверяет chat-pair.itest.ts,
 * сверяя эту функцию с least()/greatest() живой базы на случайных uuid.
 */
export function chatPairKey(x: string, y: string): { userA: string; userB: string } {
  const a = x.toLowerCase();
  const b = y.toLowerCase();
  return a <= b ? { userA: a, userB: b } : { userA: b, userB: a };
}
