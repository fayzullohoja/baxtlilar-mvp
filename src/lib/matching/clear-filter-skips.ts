import "server-only";
import { supabaseAdmin } from "@/lib/supabase/admin";
import { FILTER_REASONS, type FilterReason } from "./skip-reasons";

/**
 * Снять отказы, причина которых отпала вместе с фильтром.
 *
 * Зачем. «Не подходит по возрасту» и «не мой город» - это претензия к ФИЛЬТРУ,
 * а не к человеку. Если просто прятать кандидата навсегда, выходит ловушка:
 * человек поправил рамки, обрадовался - а лента осталась пустой, потому что все,
 * кого он отсеял по старым рамкам, скрыты насовсем. Причём винить он будет
 * приложение, и справедливо.
 *
 * Трогаем ТОЛЬКО те причины, которые действительно зависят от фильтра. Отказы
 * «просто не моё», «больше не показывать» и жалобы на анкету остаются на месте:
 * правкой рамок их не отменить, и возвращать таких людей было бы неуважением к
 * уже принятому решению.
 *
 * Вызывать надо ВЕЗДЕ, где человек меняет соответствующее предпочтение - и в
 * повторном проходе анкеты, и в будущем редакторе профиля. Забыть один из путей
 * значит оставить ловушку наполовину.
 */
export async function clearFilterSkips(
  viewerId: string,
  kinds: readonly FilterReason[],
): Promise<number> {
  if (!kinds.length) return 0;
  // Подстраховка от вызова с чужим значением: в SQL уходит только то, что
  // действительно является фильтровой причиной.
  const safe = kinds.filter((k) => (FILTER_REASONS as readonly string[]).includes(k));
  if (!safe.length) return 0;

  const { data, error } = await supabaseAdmin().rpc("clear_filter_skips", {
    p_viewer: viewerId,
    p_kinds: safe,
  });
  if (error) {
    // Не роняем сохранение предпочтений из-за побочного действия: человек
    // попросил поменять рамки, и это важнее, чем возврат скрытых карточек.
    console.error("[matching] не удалось снять фильтровые отказы:", error.message);
    return 0;
  }
  return typeof data === "number" ? data : 0;
}
