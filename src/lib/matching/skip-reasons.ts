/**
 * Причины отказа от кандидата и срок, на который он скрывается.
 *
 * Зачем это вообще. Раньше «Сейчас не подходит» прятало человека НАВСЕГДА и
 * ничего не спрашивало. При нынешнем размере это тупик: на 2026-08-25 в проде
 * 25 опубликованных анкет, из них 22 мужчины и 9 женщин. У мужчины весь запас
 * кандидатов - максимум девять человек, а дневной лимит отказов тридцать. Он
 * мог вычистить себе ленту за один присест и остаться с пустым экраном.
 *
 * Причина - не украшение и не аналитика. Она решает срок возврата, а одна из
 * причин вообще не про кандидата:
 *
 *   «не подходит по возрасту» - это претензия к ФИЛЬТРУ. Человек поставил рамки
 *   25-32, увидел 37-летнего (лестница ослабления раздвигает рамки, когда
 *   подходящих нет) и решил, что приложение сломалось. Прятать за это
 *   конкретного человека - лечить симптом. Поэтому приложение предлагает
 *   поправить рамки, а при правке такие отказы снимаются: см. clearFilterSkips
 *   и функцию clear_filter_skips в базе.
 *
 *   «не мой город» выглядит такой же жалобой на фильтр, но ею не является:
 *   geo_preference жёстко выставлен в 'my_city' и не редактируется нигде, так
 *   что чинить нечего. Поэтому обычный срок, без обещаний в интерфейсе.
 *
 * Список обязан совпадать с CHECK-ограничением match_views_reason_check -
 * расхождение ловит skip-reasons-vs-db.itest.ts. Без такой сверки пара «код
 * разрешает, база отвергает» всплывает уже на живом человеке: так было с
 * post_marriage_living, где вариант предлагался в интерфейсе и отбивался базой.
 */

export const SKIP_REASONS = [
  "age",
  "geo",
  "not_ready",
  "not_my_type",
  "profile_issue",
  "dismissed",
  "never",
] as const;

export type SkipReason = (typeof SKIP_REASONS)[number];

export function isSkipReason(v: unknown): v is SkipReason {
  return typeof v === "string" && (SKIP_REASONS as readonly string[]).includes(v);
}

const DAY_MS = 24 * 60 * 60 * 1000;

/**
 * Сколько дней кандидат скрыт. null - навсегда.
 *
 * Месяц и три месяца, а не «до конца времён» и не «неделя»: неделя не успевает
 * сменить ни настроение человека, ни его анкету, а год при пуле в девять
 * человек равен «навсегда».
 */
const HIDE_DAYS: Record<SkipReason, number | null> = {
  // Жалоба на возрастные рамки. Скрыт бессрочно, НО снимается при их правке -
  // причина отпадает вместе с фильтром (clearFilterSkips из редактора).
  age: null,
  // Гео - отдельный случай, и честный ответ здесь «пока не умеем». Поле
  // geo_preference жёстко выставлено в 'my_city' при заполнении анкеты и не
  // редактируется НИГДЕ, так что снять такой отказ правкой невозможно. Держать
  // его бессрочным значило бы обещать починку, которой нет, и молча выгрызать
  // ленту, где на человека и так приходится девять кандидатов. Поэтому обычный
  // долгий срок, как у «просто не моё».
  geo: 90,
  // Про себя, а не про кандидата: «сейчас не до этого». Через месяц человек
  // вполне может смотреть иначе.
  not_ready: 30,
  // Честное «не откликнулось». Срок длиннее - решение всё-таки про человека.
  not_my_type: 90,
  // Сигнал модерации. Показывать снова того, на кого пожаловались, нельзя:
  // разбираться с анкетой будет оператор, а не лента.
  profile_issue: null,
  // Закрыл шторку молча. Отказ засчитан, но причина неизвестна - берём мягкий
  // срок, как у «не готов»: молчание чаще значит «не хочу отвечать», а не
  // «никогда в жизни».
  dismissed: 30,
  // Осознанное «больше не показывать». Единственная причина, где «навсегда» -
  // это ровно то, что человек попросил.
  never: null,
};

/**
 * До какого момента кандидат скрыт. null - навсегда (так и лежит в базе).
 * Время передаётся снаружи, чтобы функция осталась чистой и проверяемой.
 */
export function hiddenUntil(reason: SkipReason, nowMs: number): Date | null {
  const days = HIDE_DAYS[reason];
  return days === null ? null : new Date(nowMs + days * DAY_MS);
}

/**
 * Причины, которые снимаются правкой фильтра, а не решением про человека.
 *
 * Только возраст. Гео сюда НЕ входит, хотя по смыслу просится: geo_preference
 * нигде не редактируется, снимать такой отказ нечем, и обещать это в интерфейсе
 * было бы враньём.
 */
export const FILTER_REASONS = ["age"] as const satisfies readonly SkipReason[];

export type FilterReason = (typeof FILTER_REASONS)[number];

/**
 * Причины, которые человек выбирает сам в шторке отказа.
 *
 * `dismissed` сюда не входит - его ставит сервер, когда шторку закрыли молча.
 * `never` появляется отдельно и только у кандидата, который ВЕРНУЛСЯ: предлагать
 * «больше не показывать» тому, кого видишь впервые, значит подталкивать к
 * необратимому решению на пустом месте.
 */
export const SELECTABLE_SKIP_REASONS = [
  "age",
  "geo",
  "not_ready",
  "not_my_type",
  "profile_issue",
] as const satisfies readonly SkipReason[];

/** Нужно ли после этой причины предложить поправить фильтр. */
export function suggestsFilterFix(reason: SkipReason): reason is FilterReason {
  return (FILTER_REASONS as readonly string[]).includes(reason);
}
