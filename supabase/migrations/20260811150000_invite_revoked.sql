-- Запрет приглашать на уровне ЧЕЛОВЕКА, отдельный от отметки на строке кода.
-- Найдено при ревью Task 8, закрывается в Task 10 (админка "Приглашения").
--
-- Баг, который это закрывает: гашение конкретной СТРОКИ invite_codes (кнопка
-- «Погасить» за утечку) само по себе не меняет статус человека - он остаётся
-- подтверждённым и активным. Он открывает экран «Пригласить» -> роут зовёт
-- ensureCodeForUser -> поиск активного кода ничего не находит (погашенный не
-- считается) -> без этой колонки функция создала бы ему НОВЫЙ активный код:
-- частичный индекс invite_codes_one_active_per_owner разрешает "один
-- погашенный + один новый активный" для одного owner_id. Итог без исправления:
-- мертва СТРОКА кода, но не мертво ПРАВО приглашать - гашение отменяет само
-- себя, стоит человеку открыть экран.
--
-- invite_revoked_at живёт на users, а не на invite_codes: право приглашать -
-- атрибут ЧЕЛОВЕКА, а не конкретной строки кода (у человека их за жизнь
-- аккаунта может смениться несколько). NULL = может получить код (или ждать
-- выпуска первого). Заполнено - ensureCodeForUser отказывает в выпуске НОВОГО
-- кода, пока запрет не снят явным действием оператора (restoreInviteRight,
-- src/lib/invite/store.ts).
--
-- Для бана эта колонка НЕ используется (disableCodesOfUser не трогает её при
-- reason="ban") - забаненный физически не доходит до экрана «Пригласить»
-- (requireActiveUser/loadActiveUserApi режут по lifecycle_state='blocked'
-- раньше, чем дело доходит до ensureCodeForUser), и на unban уже есть
-- симметричная пара disableCodesOfUser/reviveBanDisabledCodes (Task 8). Эта
-- колонка нужна ИМЕННО для причин, которые НЕ меняют lifecycle_state человека -
-- утечка кода и любая будущая ручная причина того же рода.
alter table users add column if not exists invite_revoked_at timestamptz;

comment on column users.invite_revoked_at is
  'Персональный запрет приглашать (гашение НЕ через бан - утечка кода и т.п.), отдельно от disabled_at строки кода. NULL = можно приглашать. Снимается явным действием оператора в /admin/invites (restoreInviteRight), не оживает сама.';
